const DICTS: Record<Lang, Dict> = { en, es, fr, tr };

export function isLang(v: unknown): v is Lang {
  return typeof v === 'string' && (LANGS as string[]).includes(v);
}

/** Translate `key` in `lang` (English fallback) and fill {0}, {1}, ... */
export function translate(lang: Lang, key: Key, ...args: (string | number)[]): string {
  const text = DICTS[lang]?.[key] ?? en[key] ?? key;
  return args.length ? text.replace(/\{(\d+)\}/g, (m, i) => (args[Number(i)] !== undefined ? String(args[Number(i)]) : m)) : text;
}

